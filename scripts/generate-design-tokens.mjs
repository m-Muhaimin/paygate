#!/usr/bin/env node
/**
 * Gate UI token generator.
 *
 * Single source of truth: src/lib/design/tokens.json
 *
 * Run (no npm script required):
 *   node scripts/generate-design-tokens.mjs
 *
 * Writes:
 *   - src/styles/gate-tokens.css                     (web: CSS custom properties + Tailwind v4 @theme)
 *   - ../paygate-android-app/.../ui/theme/Color.kt   (Compose Color vals)
 *   - ../paygate-android-app/.../ui/theme/Type.kt    (Compose TextStyle scale + Typography)
 *   - ../paygate-android-app/.../ui/theme/Shape.kt   (Compose RoundedCornerShape)
 *
 * The script is idempotent: running it twice produces byte-identical files.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const tokensPath = resolve(repoRoot, "src/lib/design/tokens.json");
const cssOut = resolve(repoRoot, "src/styles/gate-tokens.css");
const androidThemeDir = resolve(
  repoRoot,
  "..",
  "paygate-android-app",
  "app/src/main/java/com/example/ui/theme"
);

const tokens = JSON.parse(readFileSync(tokensPath, "utf8"));

const HEADER = "AUTO-GENERATED by scripts/generate-design-tokens.mjs — DO NOT EDIT BY HAND.";
const HEADER_CMD = "Edit src/lib/design/tokens.json then run: node scripts/generate-design-tokens.mjs";

/* ---------- helpers ---------- */

/**
 * camelCase token key -> kebab-case CSS suffix.
 * surface2 -> surface-2, ink2 -> ink-2, accentSoft -> accent-soft.
 * (Only surface/ink take numeric suffixes, so `h1` stays `h1`.)
 */
const kebab = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase()
    .replace(/^(surface|ink)(\d)$/, "$1-$2");

/** #RRGGBB -> 0xFFRRGGBB for Compose. */
const toCompose = (hex) => `0xFF${hex.replace("#", "").toUpperCase()}`;

/** #RRGGBB -> PascalCase identifier fragment. */
const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const COLOR_ORDER = [
  "bg",
  "surface",
  "surface2",
  "border",
  "ink",
  "ink2",
  "ink3",
  "accent",
  "accentSoft",
  "success",
  "warning",
  "danger",
];

const typeLevels = Object.entries(tokens.type);
const radiusEntries = Object.entries(tokens.radius);
const spaceEntries = Object.entries(tokens.space);

/* ---------- web: gate-tokens.css ---------- */

function colorDecls(mode, indent = "  ") {
  return COLOR_ORDER.map(
    (key) => `${indent}--gate-${kebab(key)}: ${tokens.color[mode][key]};`
  ).join("\n");
}

function providerDecls(indent = "  ") {
  return Object.entries(tokens.provider)
    .map(([k, v]) => `${indent}--gate-provider-${k}: ${v};`)
    .join("\n");
}

function fontDecls(indent = "  ") {
  return [
    `${indent}--gate-font-ui: ${JSON.stringify(tokens.font.ui)};`,
    `${indent}--gate-font-bn: ${JSON.stringify(tokens.font.bn)};`,
    `${indent}--gate-font-mono: ${JSON.stringify(tokens.font.mono)};`,
  ].join("\n");
}

function typeDecls(indent = "  ") {
  return typeLevels
    .flatMap(([name, v]) => [
      `${indent}--gate-text-${kebab(name)}: ${v.size}px;`,
      `${indent}--gate-leading-${kebab(name)}: ${v.lineHeight}px;`,
    ])
    .join("\n");
}

function radiusDecls(indent = "  ") {
  return radiusEntries
    .map(([k, v]) => `${indent}--gate-radius-${k}: ${v}px;`)
    .join("\n");
}

function spaceDecls(indent = "  ") {
  return spaceEntries
    .map(([k, v]) => `${indent}--gate-space-${k}: ${v}px;`)
    .join("\n");
}

function motionDecls(indent = "  ") {
  const m = tokens.motion;
  return [
    `${indent}--gate-duration-hover: ${m.hover}ms;`,
    `${indent}--gate-duration-state: ${m.state}ms;`,
    `${indent}--gate-duration-sheet: ${m.sheet}ms;`,
    `${indent}--gate-ease: ${m.ease};`,
  ].join("\n");
}

function colorThemeDecls(indent = "  ") {
  return COLOR_ORDER.map(
    (key) => `${indent}--color-gate-${kebab(key)}: var(--gate-${kebab(key)});`
  ).join("\n");
}

function providerThemeDecls(indent = "  ") {
  return Object.entries(tokens.provider)
    .map(([k, v]) => `${indent}--color-gate-provider-${k}: ${v};`)
    .join("\n");
}

const css = `/* ${HEADER} */
/* ${HEADER_CMD} */

:root {
  color-scheme: light;

  /* color — light */
${colorDecls("light")}

  /* provider accents (identical in both modes) */
${providerDecls()}

  /* fonts */
${fontDecls()}

  /* type scale */
${typeDecls()}

  /* radius */
${radiusDecls()}

  /* space — 4pt grid */
${spaceDecls()}

  /* motion */
${motionDecls()}
}

/* Explicit dark mode: add class="dark" to <html>. */
.dark {
  color-scheme: dark;

  /* color — dark */
${colorDecls("dark")}
}

/* System dark mode, unless the app explicitly opts into light via class="light". */
@media (prefers-color-scheme: dark) {
  :root:not(.light) {
    color-scheme: dark;
${colorDecls("dark", "    ")}
  }
}

/* Tailwind v4 theme mapping: makes bg-gate-surface, text-gate-ink,
   border-gate-border, rounded-gate-card, font-gate-mono, text-gate-h1,
   ease-gate, and gate spacing utilities available. */
@theme inline {
${colorThemeDecls()}

${providerThemeDecls()}

  /* fonts wired to next/font CSS variables in layout.tsx */
  --font-gate-ui: var(--font-inter), "Inter", ui-sans-serif, system-ui, sans-serif;
  --font-gate-bn: var(--font-bn), "Noto Sans Bengali", ui-sans-serif, sans-serif;
  --font-gate-mono: var(--font-mono), "JetBrains Mono", ui-monospace, SFMono-Regular, monospace;
${typeLevels
  .flatMap(([name, v]) => [
    `  --text-gate-${kebab(name)}: ${v.size}px;`,
    `  --text-gate-${kebab(name)}--line-height: ${v.lineHeight}px;`,
  ])
  .join("\n")}

${radiusEntries.map(([k, v]) => `  --radius-gate-${k}: ${v}px;`).join("\n")}

${spaceEntries.map(([k, v]) => `  --spacing-gate-${k}: ${v}px;`).join("\n")}

  --ease-gate: ${tokens.motion.ease};
}
`;

mkdirSync(dirname(cssOut), { recursive: true });
writeFileSync(cssOut, css, "utf8");

/* ---------- android: Color.kt ---------- */

const colorVals = [];
for (const key of COLOR_ORDER) {
  colorVals.push(`val Gate${pascal(kebab(key).replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()))}Light = Color(${toCompose(tokens.color.light[key])})`);
  colorVals.push(`val Gate${pascal(kebab(key).replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()))}Dark = Color(${toCompose(tokens.color.dark[key])})`);
}
const providerVals = Object.entries(tokens.provider).map(
  ([k, v]) => `val GateProvider${pascal(k)} = Color(${toCompose(v)})`
);

const colorKt = `package com.example.ui.theme

import androidx.compose.ui.graphics.Color

/* ${HEADER} */
/* ${HEADER_CMD} */

// ---- Gate color tokens: light ----
${colorVals.filter((l) => l.includes("Light =")).join("\n")}

// ---- Gate color tokens: dark ----
${colorVals.filter((l) => l.includes("Dark =")).join("\n")}

// ---- Provider accents ----
${providerVals.join("\n")}

// ---- Back-compat aliases (existing screens import these names) ----
val PayGateBlue = GateAccentLight
val PayGateBlueDark = Color(0xFF4646D6)
val PayGateCyan = Color(0xFF00ACC1)
val PayGateGold = Color(0xFFFFB300)

val SurfaceLight = GateBgLight
val SurfaceDark = GateBgDark
val CardLight = GateSurfaceLight
val CardDark = GateSurfaceDark

val StatusSuccess = GateSuccessLight
val StatusWarning = GateWarningLight
val StatusError = GateDangerLight
val StatusPending = GateAccentLight

val ProviderBkash = GateProviderBkash
val ProviderNagad = GateProviderNagad
val ProviderRocket = GateProviderRocket
`;

/* ---------- android: Type.kt ---------- */

const TYPE_WEIGHTS = {
  display: "SemiBold",
  h1: "SemiBold",
  h2: "SemiBold",
  h3: "SemiBold",
  body: "Normal",
  bodyMobile: "Normal",
  caption: "Normal",
  mono: "Normal",
};

const typeVals = typeLevels.map(([name, v]) => {
  const ident = `Gate${pascal(name)}`;
  const family = name === "mono" ? "FontFamily.Monospace" : "FontFamily.Default";
  const weight = `FontWeight.${TYPE_WEIGHTS[name] ?? "Normal"}`;
  return `val ${ident} =
  TextStyle(
    fontFamily = ${family},
    fontWeight = ${weight},
    fontSize = ${v.size}.sp,
    lineHeight = ${v.lineHeight}.sp,
    letterSpacing = 0.sp,
  )`;
});

const typographyMap = [
  ["displayLarge", "GateDisplay"],
  ["headlineLarge", "GateH1"],
  ["headlineMedium", "GateH2"],
  ["titleMedium", "GateH3"],
  ["bodyMedium", "GateBody"],
  ["bodyLarge", "GateBodyMobile"],
  ["labelSmall", "GateCaption"],
  ["labelMedium", "GateMono"],
]
  .map(([k, v]) => `    ${k} = ${v},`)
  .join("\n");

const typeKt = `package com.example.ui.theme

import androidx.compose.material3.Typography
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.sp

/* ${HEADER} */
/* ${HEADER_CMD} */

// Gate type scale. Android falls back to the platform sans / monospace family;
// ship Inter + Noto Sans Bengali + JetBrains Mono as resources for exact parity.

${typeVals.join("\n\n")}

val Typography =
  Typography(
${typographyMap}
  )
`;

/* ---------- android: Shape.kt ---------- */

const shapeVals = radiusEntries
  .map(([k, v]) => `val GateShape${pascal(k)} = RoundedCornerShape(${v}.dp)`)
  .join("\n");

const shapeKt = `package com.example.ui.theme

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.ui.unit.dp

/* ${HEADER} */
/* ${HEADER_CMD} */

// Gate shape scale: 4pt grid — 8 inputs/chips, 12 buttons, 16 cards, 24 sheets, full pills.
${shapeVals}
`;

mkdirSync(androidThemeDir, { recursive: true });
writeFileSync(resolve(androidThemeDir, "Color.kt"), colorKt, "utf8");
writeFileSync(resolve(androidThemeDir, "Type.kt"), typeKt, "utf8");
writeFileSync(resolve(androidThemeDir, "Shape.kt"), shapeKt, "utf8");

const slash = (p) => p.replace(/\\/g, "/");
console.log("gate-tokens: wrote");
console.log(`  - ${slash(cssOut)}`);
console.log(`  - ${slash(resolve(androidThemeDir, "Color.kt"))}`);
console.log(`  - ${slash(resolve(androidThemeDir, "Type.kt"))}`);
console.log(`  - ${slash(resolve(androidThemeDir, "Shape.kt"))}`);
